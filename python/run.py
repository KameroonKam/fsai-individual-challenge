"""
Runs your solution.py and writes its results to output/.

DO NOT EDIT THIS FILE. The marking harness replaces it with its own copy and
runs it on the data you were given and on a second, unseen track.

    python python/run.py 1      # Task 1  -> output/cones.csv
    python python/run.py 2a     # Task 2a -> output/racing_line.csv
    python python/run.py 2b     # Task 2b -> output/projections.csv
    python python/run.py all    # every task you have implemented

Options: --data DIR (default data/), --out DIR (default output/)
"""
from __future__ import annotations

import argparse
import csv
import math
import sys
import time
import traceback
from numbers import Real
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from challenge_io import DATA_DIR, OUTPUT_DIR, load_camera, load_frames, load_trajectory  # noqa: E402


class InterfaceError(Exception):
    """Your function returned something run.py can't use."""


def _num(v, what):
    if isinstance(v, bool) or not isinstance(v, Real):
        try:                                   # numpy scalars etc.
            v = float(v)
        except (TypeError, ValueError):
            raise InterfaceError(f"{what} should be a number, got {type(v).__name__}: {v!r}")
    v = float(v)
    if not math.isfinite(v):
        raise InterfaceError(f"{what} is {v}")
    return v


def _seq(v, n, what):
    try:
        items = list(v)
    except TypeError:
        raise InterfaceError(f"{what} should be a tuple of {n} values, got {type(v).__name__}: {v!r}")
    if len(items) != n:
        raise InterfaceError(f"{what} should have {n} values, got {len(items)}: {v!r}")
    return items


def _read_cones(path):
    """The runner's own cone reader, so Tasks 2a/2b are marked independently of Task 1."""
    with open(path, newline="") as f:
        rows = list(csv.reader(f))
    return [(r[0].strip(), float(r[1]), float(r[2])) for r in rows[1:] if r]


def _write(path, header, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


# --------------------------------------------------------------------------- tasks
def task_1(solution, data, out):
    result = solution.parse_cones(str(data / "track.csv"))
    rows = []
    for i, c in enumerate(result):
        side, x, y = _seq(c, 3, f"cone {i}")
        if not isinstance(side, str):
            raise InterfaceError(f"cone {i}: side should be a string, got {side!r}")
        rows.append((side, f"{_num(x, f'cone {i} x'):.6f}", f"{_num(y, f'cone {i} y'):.6f}"))
    _write(out / "cones.csv", ["side", "x", "y"], rows)
    return f"{len(rows)} cones"


def task_2a(solution, data, out):
    result = solution.plan_racing_line(_read_cones(data / "track.csv"))
    rows = []
    for i, p in enumerate(result):
        x, y = _seq(p, 2, f"point {i}")
        rows.append((f"{_num(x, f'point {i} x'):.6f}", f"{_num(y, f'point {i} y'):.6f}"))
    if len(rows) < 3:
        raise InterfaceError(f"racing line has only {len(rows)} points")
    _write(out / "racing_line.csv", ["x", "y"], rows)
    return f"{len(rows)} points"


def task_2b(solution, data, out):
    cones = _read_cones(data / "track.csv")
    camera = load_camera(data / "camera.json")
    trajectory = load_trajectory(data / "trajectory.csv")
    rows = []
    for t in load_frames(data / "frames.csv"):
        result = solution.project_cones(cones, trajectory[t], camera)
        for j, p in enumerate(result):
            k, u, v = _seq(p, 3, f"frame {t}, item {j}")
            k_f = _num(k, f"frame {t}, item {j} cone_index")
            if k_f != int(k_f) or not 0 <= k_f < len(cones):
                raise InterfaceError(f"frame {t}, item {j}: cone_index {k!r} is not a valid index")
            rows.append((t, int(k_f), f"{_num(u, 'u'):.3f}", f"{_num(v, 'v'):.3f}"))
    _write(out / "projections.csv", ["timestamp_ms", "cone_index", "u", "v"], rows)
    return f"{len(rows)} projections"


TASKS = {"1": task_1, "2a": task_2a, "2b": task_2b}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("task", choices=[*TASKS, "all"])
    p.add_argument("--data", type=Path, default=DATA_DIR)
    p.add_argument("--out", type=Path, default=OUTPUT_DIR)
    a = p.parse_args(argv)

    import solution  # imported here so a broken solution.py still gives a clear message

    status = {}
    for name in (TASKS if a.task == "all" else [a.task]):
        start = time.perf_counter()
        try:
            msg = TASKS[name](solution, a.data, a.out)
            status[name] = "ok"
            print(f"Task {name}: ok, {msg} ({time.perf_counter() - start:.2f} s)")
        except NotImplementedError:
            status[name] = "not implemented"
            print(f"Task {name}: not implemented")
        except InterfaceError as e:
            status[name] = "interface error"
            print(f"Task {name}: INTERFACE ERROR: {e}")
        except Exception:
            status[name] = "crashed"
            print(f"Task {name}: CRASHED")
            traceback.print_exc()
    # 'all' succeeds if nothing crashed; a single task must actually run
    bad = {"crashed", "interface error"} if a.task == "all" else {"crashed", "interface error", "not implemented"}
    return 1 if bad & set(status.values()) else 0


if __name__ == "__main__":
    sys.exit(main())
