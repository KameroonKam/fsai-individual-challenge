"""
Helpers for reading the Task 2b data files.

DO NOT EDIT THIS FILE. The marking harness replaces it with its own copy.
You are welcome to import it from your own code (e.g. main.py).
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = REPO_ROOT / "data"
OUTPUT_DIR = REPO_ROOT / "output"


def load_camera(path: str | Path) -> dict:
    """camera.json as a dict:
    {"image_width", "image_height", "fx", "fy", "cx", "cy",
     "mount": {"forward_offset_m", "height_m", "pitch_rad"}}"""
    with open(path) as f:
        return json.load(f)


def load_trajectory(path: str | Path) -> dict[int, tuple[float, float, float]]:
    """trajectory.csv as {timestamp_ms: (x, y, yaw)}, in file order."""
    poses: dict[int, tuple[float, float, float]] = {}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            poses[int(row["timestamp_ms"])] = (float(row["x"]), float(row["y"]), float(row["yaw"]))
    return poses


def load_frames(path: str | Path) -> list[int]:
    """frames.csv as a list of timestamps (ms)."""
    with open(path, newline="") as f:
        return [int(row["timestamp_ms"]) for row in csv.DictReader(f)]
